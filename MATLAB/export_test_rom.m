%% export_test_rom.m
% Builds the test-signal ROM for the FPGA demo (hfma_top_test.vhd).
% Makes a plane wave from your speech recording at a few DOAs, quantises it
% to the core's input format (sfix16_En15) and writes a VHDL package:
%     hfma_test_rom_pkg.vhd
% Each ROM word = [Mic4 Mic3 Mic2 Mic1], 16 bits each.
%
% The FPGA cycles through the angles (4 s each) and shows
%     [true angle]  [estimated DOA]   on the 7-segment display.

ANGLES     = [-60 -20 30 70];        % test DOAs (deg) - change freely, 1 to 4 of them
NSAMP_LOG2 = 11;                     % 2^11 = 2048 samples per angle (0.256 s, loops)
WAV_FILE   = 'Testing 28-07/0.wav';
OUT_FILE   = 'hfma_test_rom_pkg.vhd';

fs = 8000; Na = 4; NSAMP = 2^NSAMP_LOG2;

% --- speech segment (same selection as the sweep script) -------------------
[s1, fs_in] = audioread(WAV_FILE);
s1  = resample(s1(:,1), fs, fs_in);
i0  = find(abs(s1) > 0.1*max(abs(s1)), 1);
assert(i0 + NSAMP - 1 <= numel(s1), 'Recording too short');
s   = s1(i0:i0+NSAMP-1);
s   = s / max(abs(s));

% --- plane waves, quantised to sfix16_En15 ----------------------------------
words = strings(numel(ANGLES)*NSAMP, 1);
for a = 1:numel(ANGLES)
    sig = ULA_planewave(s, deg2rad(ANGLES(a)), Na, fs);   % circular delays -> loops seamlessly
    pk  = max(abs(sig(:)));
    if pk > 0.999, sig = sig * (0.999/pk); end
    q   = round(sig * 2^15);
    q   = min(max(q, -2^15), 2^15-1);
    u   = double(typecast(int16(q(:)), 'uint16'));
    u   = reshape(u, NSAMP, Na);
    for n = 1:NSAMP
        words((a-1)*NSAMP + n) = sprintf('x"%04X%04X%04X%04X"', ...
            u(n,4), u(n,3), u(n,2), u(n,1));
    end
end

% --- write the VHDL package --------------------------------------------------
fid = fopen(OUT_FILE, 'w');
fprintf(fid, '-- Auto-generated by export_test_rom.m on %s\n', datestr(now));
fprintf(fid, '-- Test DOAs: %s deg, %d samples each, word = [Mic4 Mic3 Mic2 Mic1] sfix16_En15\n', ...
        mat2str(ANGLES), NSAMP);
fprintf(fid, 'library IEEE;\nuse IEEE.STD_LOGIC_1164.ALL;\n\n');
fprintf(fid, 'package hfma_test_rom_pkg is\n');
fprintf(fid, '  constant NANG       : natural := %d;\n', numel(ANGLES));
fprintf(fid, '  constant NSAMP_LOG2 : natural := %d;\n', NSAMP_LOG2);
fprintf(fid, '  constant NSAMP      : natural := 2**NSAMP_LOG2;\n');
fprintf(fid, '  type int_arr is array (0 to NANG-1) of integer;\n');
if numel(ANGLES) == 1
    fprintf(fid, '  constant TRUE_ANGLES : int_arr := (0 => %d);\n', ANGLES);
else
    fprintf(fid, '  constant TRUE_ANGLES : int_arr := (%s);\n', strjoin(string(ANGLES), ', '));
end
fprintf(fid, '  type rom_t is array (0 to NANG*NSAMP-1) of std_logic_vector(63 downto 0);\n');
fprintf(fid, '  constant TEST_ROM : rom_t := (\n');
for k = 1:numel(words)
    if k < numel(words), sep = ','; else, sep = ''; end
    fprintf(fid, '    %s%s\n', words(k), sep);
end
fprintf(fid, '  );\nend package;\n');
fclose(fid);
fprintf('Wrote %s  (%d angles x %d samples)\n', OUT_FILE, numel(ANGLES), NSAMP);

%% ------------------------------------------------------------------------
function w = ULA_planewave(x, DOA, Na, fs)
    c = 343; d = 0.042;
    Tau = (d/c)*sin(DOA);
    lh = length(x);
    f = (-lh/2 : lh/2-1)' * (fs/lh);
    omega = 2*pi*f;
    X = fftshift(fft(x));
    w = zeros(lh, Na);  w(:,1) = x;
    for p = 2:Na
        w(:,p) = ifft(ifftshift(X .* exp(-1j*omega*(p-1)*Tau)), 'symmetric');
    end
end
